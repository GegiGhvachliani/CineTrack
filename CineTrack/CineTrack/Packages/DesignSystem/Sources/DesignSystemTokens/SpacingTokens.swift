import CoreGraphics  // არა SwiftUI ან Foundation-ს რადგან მხოლოდ CGFloat გვჭირდება და ტყულად დავაიმპორტებთ

// 💡 ოქროს წესი SwiftUI-ში დიზაინის აწყობისას:
// Spacing.regular (16pt) გამოიყენე თითქმის ყველა ეკრანის გვერდითა ჩარჩოებისთვის: .padding(.horizontal, Spacing.regular).
//
// პატარა დაშორებებისთვის (ტექსტი + იკონკა) იტრიალე 4, 8, 12-ს შორის.
//
// ეკრანზე დიდი ბლოკების და ღილაკების დასასმელად გამოიყენე 24, 32, 48.

public enum SpacingTokens {

    /// **4pt — ძალიან მცირე, მიკრო დაშორებები**
    /// - *გამოყენება:* ფილმის პატარა ვარსკვლავსა (Icon) და რეიტინგის ციფრს (Text) შორის დაშორება.
    public static let xSmall: CGFloat = 4

    /// **8pt — მცირე შიდა დაშორებები (Padding) ან ელემენტების ჯგუფები**
    /// - *გამოყენება:* ჟანრის თეგის (Chip) შიდა პადინგი, ან მსახიობის ფოტოსა და მის სახელს შორის დაშორება სიაში.
    public static let small: CGFloat = 8

    /// **12pt — საშუალო დაშორება მსგავს ელემენტებს შორის**
    /// - *გამოყენება:* ჰორიზონტალურ სიაში (Carousel) ფილმის ბარათებს შორის დაშორება, ან თეგების (Chips) ერთმანეთთან დაშორება Grid-ში.
    public static let medium: CGFloat = 12

    /// **16pt — სტანდარტული გვერდითა დაშორება (Standard Screen Padding)**
    /// - *გამოყენება:* ყველაზე მნიშვნელოვანი ზომაა. ეკრანის კიდეებიდან (მარცხნიდან და მარჯვნიდან) მთელი კონტენტის დაშორება (Safe Area-ს შიგნით).
    public static let regular: CGFloat = 16

    /// **20pt — გაზრდილი სტანდარტული დაშორება**
    /// - *გამოყენება:* ონბორდინგის მთავარ დიდ სათაურსა (Large Title) და მის ქვედა აღწერას (Body Text) შორის დაშორება.
    public static let large: CGFloat = 20

    /// **24pt — დიდი გამოყოფა სხვადასხვა ბლოკებს შორის**
    /// - *გამოყენება:* ფილმის დეტალების ეკრანზე სხვადასხვა სექციების ერთმანეთისგან დაშორება (მაგალითად, აღწერის ბლოკსა და Cast-ის სიას შორის).
    public static let xLarge: CGFloat = 24

    /// **32pt — ძალიან დიდი დაშორება სექციებს შორის**
    /// - *გამოყენება:* ონბორდინგში ჟანრების ასარჩევ ბადესა (Grid) და ქვედა "Continue" ღილაკს შორის თავისუფალი სივრცე.
    public static let xxLarge: CGFloat = 32

    /// **40pt — მაკრო დაშორება მთავარი კომპონენტებისთვის**
    /// - *გამოყენება:* ონბორდინგის ილუსტრაციასა და მის ქვემოთ დაწყებულ ტექსტებს შორის დიდი, სუფთა სივრცის დატოვება.
    public static let xxxLarge: CGFloat = 40

    /// **48pt — უზარმაზარი დაშორება აპლიკაციის კიდეებიდან**
    /// - *გამოყენება:* ონბორდინგის ქვედა ღილაკის დაშორება ეკრანის სულ ქვედა კიდიდან (Bottom SafeArea-დან), რომ ღილაკი ძალიან დაბლა არ დაჯდეს.
    public static let huge: CGFloat = 48

    /// **64pt — მაქსიმალური დაშორება ეკრანის ზედა ნაწილისთვის**
    /// - *გამოყენება:* ონბორდინგის პირველ ეკრანზე (Discover) ეკრანის სულ ზედა კიდიდან (Top SafeArea) პირველ ელემენტამდე (ან ლოგომდე) დასაშორებლად.
    public static let massive: CGFloat = 64
}
